ADVANCE = 6  # glyph width (5) + 1 pixel of spacing


def text_width(s, scale):
    return (len(s) * ADVANCE - 1) * scale


def _runs(rows, x, y, scale, want):
    """Merge horizontal runs of `want` characters into SVG path commands."""
    d = []
    for ry, row in enumerate(rows):
        rx = 0
        while rx < len(row):
            if row[rx] == want:
                start = rx
                while rx < len(row) and row[rx] == want:
                    rx += 1
                w = (rx - start) * scale
                d.append(f"M{x + start * scale:g} {y + ry * scale:g}h{w:g}v{scale:g}h-{w:g}z")
            else:
                rx += 1
    return "".join(d)


def text(s, x, y, scale, fill, extra=""):
    """Render a string in the pixel font as a single <path>. (x, y) = top-left."""
    s = s.upper()
    d = []
    for i, ch in enumerate(s):
        glyph = FONT.get(ch, FONT["?"])
        d.append(_runs(glyph, x + i * ADVANCE * scale, y, scale, "#"))
    return f'<path d="{"".join(d)}" fill="{fill}" {extra}/>'


def text_centered(s, cx, y, scale, fill, extra=""):
    return text(s, cx - text_width(s, scale) / 2, y, scale, fill, extra)


def sprite(rows, palette, x, y, scale, extra=""):
    """Render a sprite (list of strings; '.' = transparent) as one <path> per colour."""
    out = []
    for key, color in palette.items():
        d = _runs(rows, x, y, scale, key)
        if d:
            out.append(f'<path d="{d}" fill="{color}"/>')
    return f'<g {extra}>{"".join(out)}</g>'


def mirror(rows):
    return [r[::-1] for r in rows]
